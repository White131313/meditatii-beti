export const getRandomNoun = (difficulty) => {
    let pool = ARTICLE_NOUNS.filter(n => n.difficulty === difficulty);

    if (pool.length === 0) {
        pool = ARTICLE_NOUNS.filter(n => n.difficulty === 'easy');
    }

    if (pool.length === 0) {
        return {
            difficulty: 'easy',
            noun: 'Carte',
            translation_hu: 'Könyv',
            correct_article: 'O',
            gender_explanation: 'Carte este un substantiv feminin.'
        };
    }

    return pool[Math.floor(Math.random() * pool.length)];
};
