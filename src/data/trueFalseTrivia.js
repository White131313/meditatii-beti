export const getRandomTrivia = (difficulty) => {
    let pool = TRUE_FALSE_TRIVIA.filter(t => t.difficulty === difficulty);

    // Fallback if pool is empty
    if (pool.length === 0) {
        pool = TRUE_FALSE_TRIVIA.filter(t => t.difficulty === 'easy');
    }

    // Ultimate fallback to avoid crashes
    if (pool.length === 0) {
        return {
            difficulty: 'easy',
            statement: "Soarele este galben. ☀️",
            isTrue: true,
            explanation: "Soarele strălucește pe cer.",
            translation_hu: "A nap sárga."
        };
    }

    return pool[Math.floor(Math.random() * pool.length)];
};
